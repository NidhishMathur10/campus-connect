/** "Due in 3 hours" / "Late by 1 hour" in plain words. */
export function timeLeftWords(
  t: Text,
  dueAt: string | null,
  now: number,
): { text: string; late: boolean; soon: boolean } | null {
  if (!dueAt) return null;
  const diff = new Date(dueAt).getTime() - now;
  const mins = Math.max(1, Math.round(Math.abs(diff) / 60_000));
  let words: string;
  if (mins < 60) words = t.unitMinute(mins);
  else if (mins < 48 * 60) words = t.unitHour(Math.round(mins / 60));
  else words = t.unitDay(Math.round(mins / 1440));
  return diff < 0
    ? { text: t.lateBy(words), late: true, soon: false }
    : { text: t.dueIn(words), late: false, soon: diff < 60 * 60_000 };
}
