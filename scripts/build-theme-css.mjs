// Generates src/app/globals.css from scripts/theme-tokens.json (the one source of truth for colours).
// Run: node scripts/build-theme-css.mjs
import { readFileSync, writeFileSync } from "node:fs";

const T = JSON.parse(readFileSync(new URL("./theme-tokens.json", import.meta.url), "utf8"));

function block(i) {
  const out = [];
  for (const [k, v] of Object.entries(T.core)) out.push(`  --${k}: ${v[i]};`);
  for (const [k, v] of Object.entries(T.pairs)) {
    out.push(`  --${k}-bg: ${v[i === 0 ? 0 : 2]};`);
    out.push(`  --${k}-fg: ${v[i === 0 ? 1 : 3]};`);
  }
  for (const [k, v] of Object.entries(T.charts)) out.push(`  --${k}: ${v[i]};`);
  return out.join("\n");
}

const theme = [];
const alias = (name, from) => theme.push(`  --color-${name}: var(--${from});`);

for (const n of [
  "surface", "surface-2", "surface-accent", "surface-accent-2", "surface-inverse",
  "text", "text-muted", "text-inverse", "text-inverse-muted",
  "primary", "primary-fg", "accent-fg", "accent-text",
  "input-bg", "input-border", "placeholder", "border", "ring", "star",
  "info-on-inverse", "warning-on-inverse",
  "danger-solid", "danger-solid-fg", "warning-solid", "warning-solid-fg", "success-solid", "success-solid-fg", "scrim",
]) alias(n, n);
theme.push(
  "  --color-page: var(--bg);",
  "  --color-accent-blue: var(--accent);",
  "  --color-accent-violet: var(--accent-2);",
  "  --color-accent-violet-text: var(--accent-2-text);",
);
// shadcn/ui component compatibility (they use background / card / muted / ...).
for (const [n, v] of [
  ["background", "bg"], ["foreground", "text"], ["card", "surface"], ["card-foreground", "text"],
  ["popover", "popover"], ["popover-foreground", "text"], ["primary-foreground", "primary-fg"],
  ["secondary", "surface-accent"], ["secondary-foreground", "text"], ["muted", "surface-2"],
  ["muted-foreground", "text-muted"], ["accent", "surface-2"], ["accent-foreground", "text"],
  ["destructive", "danger-fg"], ["input", "input-border"],
  ["sidebar", "surface"], ["sidebar-foreground", "text"], ["sidebar-border", "border"],
  ["sidebar-primary", "primary"], ["sidebar-primary-foreground", "primary-fg"],
  ["sidebar-accent", "surface-2"], ["sidebar-accent-foreground", "text"], ["sidebar-ring", "ring"],
  ["chart-1", "chart-1"], ["chart-2", "chart-2"], ["chart-3", "chart-3"], ["chart-4", "chart-4"], ["chart-5", "chart-5"],
]) alias(n, v);
for (const k of Object.keys(T.pairs)) {
  alias(`${k}-bg`, `${k}-bg`);
  alias(`${k}-fg`, `${k}-fg`);
}

const css = `@import "tailwindcss";
@import "tw-animate-css";
@import "shadcn/tailwind.css";

@custom-variant dark (&:is(.dark *));

/*
 * GENERATED by scripts/build-theme-css.mjs from scripts/theme-tokens.json. Edit the JSON, not this block.
 * Components only use the semantic utilities mapped in @theme inline (bg-surface, text-text-muted,
 * bg-warning-bg + text-warning-fg, ...), never raw palette colours (npm run check:theme enforces it).
 * Rule: every background token is used with its matching foreground token.
 */
@theme inline {
  --font-sans: var(--font-manrope), "DM Sans", ui-sans-serif, system-ui, sans-serif;
  --font-mono: ui-monospace, SFMono-Regular, Menlo, monospace;
  --font-heading: var(--font-manrope), "DM Sans", ui-sans-serif, system-ui, sans-serif;

  --shadow-float: 0 8px 30px -12px var(--shadow-color);
  --shadow-card: 0 1px 2px var(--shadow-color-soft), 0 8px 24px -12px var(--shadow-color);
  --shadow-glow: 0 0 0 6px var(--glow);

  --color-navy: var(--surface-inverse);
${theme.join("\n")}

  --radius-sm: calc(var(--radius) * 0.6);
  --radius-md: calc(var(--radius) * 0.8);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) * 1.4);
  --radius-2xl: calc(var(--radius) * 1.8);
  --radius-3xl: calc(var(--radius) * 2.2);
  --radius-4xl: calc(var(--radius) * 2.6);

  --animate-fade-in: fade-in 0.4s ease-out both;
  --animate-slide-up: slide-up 0.45s cubic-bezier(0.22, 1, 0.36, 1) both;

  @keyframes fade-in {
    from { opacity: 0; }
    to { opacity: 1; }
  }
  @keyframes slide-up {
    from { opacity: 0; transform: translateY(10px); }
    to { opacity: 1; transform: translateY(0); }
  }
}

:root {
  /* ===== Light (our original design) ===== */
${block(0)}
  --radius: 0.75rem;
  color-scheme: light;
}

.dark {
  /* ===== Dark ===== */
${block(1)}
  color-scheme: dark;
}

@layer base {
  * {
    @apply border-border outline-ring/50;
  }
  html {
    @apply font-sans;
  }
  body {
    background-color: var(--bg);
    color: var(--text);
    /* faint grid pattern */
    background-image:
      linear-gradient(to right, var(--grid-line) 1px, transparent 1px),
      linear-gradient(to bottom, var(--grid-line) 1px, transparent 1px);
    background-size: 32px 32px;
    background-attachment: fixed;
  }
  button:not(:disabled),
  [role="button"]:not(:disabled) {
    cursor: pointer;
  }
  ::placeholder {
    color: var(--placeholder);
    opacity: 1;
  }
}

@layer components {
  /* Small uppercase letter-spaced label, e.g. "AI SUMMARY" */
  .eyebrow {
    @apply text-[11px] font-bold tracking-[0.14em] text-text-muted uppercase;
  }
}
`;

writeFileSync(new URL("../src/app/globals.css", import.meta.url), css);
console.log("wrote src/app/globals.css");
